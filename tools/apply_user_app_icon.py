"""Adapt user-supplied artwork into Android launcher icons; never generates art."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import shutil
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'build-local/icon-python'))
from PIL import Image, ImageDraw, ImageFilter, ImageOps

BACKGROUND = (12, 43, 45, 255)
DENSITIES = {'mdpi': 1, 'hdpi': 1.5, 'xhdpi': 2, 'xxhdpi': 3, 'xxxhdpi': 4}


def compose(art: Image.Image, side: int, art_fraction: float, opaque: bool) -> Image.Image:
    canvas = Image.new('RGBA', (side, side), BACKGROUND if opaque else (0, 0, 0, 0))
    fitted = ImageOps.contain(art, (round(side * art_fraction), round(side * art_fraction)), Image.Resampling.LANCZOS)
    # Blend only the outermost artwork edge into the launcher background.
    mask = Image.new('L', fitted.size, 0)
    edge = max(1, round(fitted.width * 0.012))
    ImageDraw.Draw(mask).rectangle((edge, edge, fitted.width - edge - 1, fitted.height - edge - 1), fill=255)
    mask = mask.filter(ImageFilter.GaussianBlur(edge / 2))
    fitted.putalpha(mask)
    canvas.alpha_composite(fitted, ((side - fitted.width) // 2, (side - fitted.height) // 2))
    return canvas


def shaped(image: Image.Image, circular: bool) -> Image.Image:
    side = image.width
    mask = Image.new('L', image.size, 0)
    draw = ImageDraw.Draw(mask)
    if circular:
        draw.ellipse((0, 0, side - 1, side - 1), fill=255)
    else:
        draw.rounded_rectangle((0, 0, side - 1, side - 1), radius=round(side * 0.20), fill=255)
    result = image.copy()
    result.putalpha(mask)
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path)
    parser.add_argument('--output', type=Path, default=ROOT / 'artwork/user-icon-v4')
    args = parser.parse_args()
    source = args.source.resolve(strict=True)
    output = args.output.resolve()
    if output.exists():
        raise RuntimeError(f'Refusing to overwrite an existing artwork output directory: {output}')
    with Image.open(source) as original:
        original.load()
        art = ImageOps.exif_transpose(original).convert('RGBA')
    output.mkdir(parents=True)
    shutil.copy2(source, output / 'source.png')
    res = ROOT / 'upstream/android/app/src/main/res'
    backup = output / 'previous-resources'
    master = compose(art, 1024, 0.88, True)
    foreground = compose(art, 1296, 0.88 * 72 / 108, False)
    for density, factor in DENSITIES.items():
        directory = res / ('mipmap-' + density)
        for filename, pixels, image in [
            ('ic_launcher.png', round(48 * factor), shaped(master, False)),
            ('ic_launcher_round.png', round(48 * factor), shaped(master, True)),
            ('ic_launcher_foreground.png', round(108 * factor), foreground),
        ]:
            target = directory / filename
            # Read and preserve every overwritten asset before replacement.
            with Image.open(target) as existing:
                existing.verify()
            preserved = backup / directory.name / filename
            preserved.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(target, preserved)
            image.resize((pixels, pixels), Image.Resampling.LANCZOS).save(target, optimize=True)
    shaped(master, False).save(output / 'preview-square.png', optimize=True)
    shaped(master, True).save(output / 'preview-round.png', optimize=True)
    shaped(master, True).resize((192, 192), Image.Resampling.LANCZOS).save(output / 'preview-round-192.png')
    shaped(master, False).resize((48, 48), Image.Resampling.LANCZOS).save(output / 'preview-square-48.png')
    # Match the legacy previews to the visible 72dp adaptive-icon viewport.
    visible = Image.new('RGBA', (1296, 1296), BACKGROUND)
    visible.alpha_composite(foreground)
    visible = visible.crop((216, 216, 1080, 1080)).resize((1024, 1024), Image.Resampling.LANCZOS)
    shaped(visible, True).save(output / 'preview-adaptive-round.png')
    report = {
        'provenance': 'User supplied artwork; resized and padded, not generated by this agent.',
        'source_sha256': hashlib.sha256(source.read_bytes()).hexdigest(),
        'source_dimensions': list(art.size),
        'background_rgba': list(BACKGROUND),
        'artwork_fraction_of_visible_icon': 0.88,
        'adaptive_foreground_fraction': 0.88 * 72 / 108,
        'resource_count': len(DENSITIES) * 3,
    }
    (output / 'provenance.json').write_text(json.dumps(report, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print(json.dumps(report, ensure_ascii=False, indent=2))
    print(f'Artwork and previews: {output}')


if __name__ == '__main__':
    main()
